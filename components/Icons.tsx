export function PlatformBadge({ service }: { service: string }) {
  const norm = (service || "").toLowerCase();
  if (norm.includes("twitter") || norm === "x") {
    return <span className="px-2 py-0.5 text-xs font-semibold rounded bg-sky-500/10 text-sky-400 border border-sky-500/30">X / Twitter</span>;
  }
  if (norm.includes("linkedin")) {
    return <span className="px-2 py-0.5 text-xs font-semibold rounded bg-blue-600/10 text-blue-400 border border-blue-600/30">LinkedIn</span>;
  }
  if (norm.includes("threads")) {
    return <span className="px-2 py-0.5 text-xs font-semibold rounded bg-purple-500/10 text-purple-400 border border-purple-500/30">Threads</span>;
  }
  if (norm.includes("instagram")) {
    return <span className="px-2 py-0.5 text-xs font-semibold rounded bg-pink-500/10 text-pink-400 border border-pink-500/30">Instagram</span>;
  }
  return <span className="px-2 py-0.5 text-xs font-semibold rounded bg-slate-500/10 text-slate-300 border border-slate-500/30">{service}</span>;
}
